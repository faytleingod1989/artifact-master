import { test, expect } from '@playwright/test'
import { CHARACTER_PROFILES } from '../src/characters/profiles'

test('all released profiles use distinct contained originals and selected rules survive navigation', async ({ page }) => {
  const errors: string[] = []
  page.on('pageerror', error => errors.push(error.message))
  page.on('console', message => { if (message.type() === 'error') errors.push(message.text()) })
  await page.setViewportSize({ width: 1440, height: 980 })
  await page.goto('/')
  await expect(page.getByText('已保存', { exact: true })).toBeVisible()
  const nav = (name: string) => page.getByRole('navigation', { name: '主导航', exact: true }).getByRole('button', { name, exact: true }).click()
  await nav('角色配装')
  await expect(page).toHaveTitle(/圣遗物|星穹/)
  await expect(page.getByRole('heading', { name: '角色档案 121 位' })).toBeVisible()
  const sources = []
  for (const profile of CHARACTER_PROFILES) {
    const img = page.getByRole('img', { name: `${profile.name} 的头像`, exact: true })
    await expect(img).toHaveJSProperty('naturalWidth', 256)
    await expect(img).toHaveJSProperty('naturalHeight', 256)
    expect(await img.evaluate(el => getComputedStyle(el).objectFit)).toBe('contain')
    sources.push(await img.getAttribute('src'))
  }
  expect(new Set(sources).size).toBe(121)
  await expect(page.locator('vite-error-overlay')).toHaveCount(0)
  await expect(page).toHaveURL('http://127.0.0.1:4178/')
  await page.getByLabel('搜索角色').fill('沃雅')
  await page.getByRole('button', { name: /沃雅妮莎/ }).click()
  await page.getByLabel('配装玩法', { exact: true }).selectOption('hp-team')
  await expect(page.getByText('千岩牢固×2 + 花海甘露之光×2', { exact: true })).toBeVisible()
  await page.getByRole('button', { name: '查看该角色推荐' }).click()
  await expect(page.getByLabel('配装玩法', { exact: true })).toHaveValue('hp-team')
  await expect(page.getByText(/没有可用的完整建议套装/)).toBeVisible()
  await page.getByRole('button', { name: '更换角色' }).click()
  await expect(page.getByLabel('配装玩法', { exact: true })).toHaveValue('hp-team')
  await page.screenshot({ path: 'C:/Users/Administrator/AppData/Local/Temp/ys-characters-desktop.png', fullPage: false })
  await page.getByLabel('搜索角色').fill('雷电')
  await page.getByRole('button', { name: /雷电将军/ }).click()
  await expect(page.getByLabel('配装玩法', { exact: true })).toHaveValue('burst')
  await page.getByLabel('配装玩法', { exact: true }).selectOption('hyperbloom')
  await expect(page.getByText('元素精通', { exact: true }).first()).toBeVisible()
  await page.setViewportSize({ width: 370, height: 850 })
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
  await page.screenshot({ path: 'C:/Users/Administrator/AppData/Local/Temp/ys-characters-mobile.png', fullPage: false })
  expect(errors).toEqual([])
})

test('element categories keep five-stars first, support both release directions and select the matching Traveler form', async ({ page }) => {
  await page.setViewportSize({ width: 1440, height: 980 })
  await page.goto('/')
  await expect(page.getByText('已保存', { exact: true })).toBeVisible()
  await page.getByRole('navigation', { name: '主导航', exact: true }).getByRole('button', { name: '角色配装', exact: true }).click()
  await page.getByRole('button', { name: /^风元素/ }).click()
  const names = () => page.locator('.character-directory [data-character-name]').evaluateAll(nodes => nodes.map(el => el.getAttribute('data-character-name')))
  const stars = await page.locator('.character-directory [data-rarity]').evaluateAll(nodes => nodes.map(el => Number(el.getAttribute('data-rarity'))))
  expect(stars).toEqual([...stars].sort((a,b) => b-a))
  expect((await names()).indexOf('布伦妮')).toBeLessThan((await names()).indexOf('雅珂达'))
  await page.getByLabel('角色新旧排序').selectOption('oldest')
  const older = await names()
  expect(older.indexOf('温迪')).toBeLessThan(older.indexOf('枫原万叶'))
  expect(older.indexOf('雅珂达')).toBeLessThan(older.indexOf('布伦妮'))
  expect(older.indexOf('法尔伽')).toBeLessThan(older.indexOf('早柚'))
  await page.getByRole('button', { name: /^冰元素/ }).click()
  await page.getByLabel('搜索角色').fill('旅行者')
  await page.getByRole('button', { name: /旅行者.*5★/ }).click()
  await expect(page.getByLabel('配装玩法', { exact: true })).toHaveValue('cryo')
  await expect(page.getByText(/5★ · 冰元素 · 单手剑/)).toBeVisible()
  await page.getByLabel('配装玩法', { exact: true }).selectOption('dendro')
  await expect(page.getByText(/5★ · 草元素 · 单手剑/)).toBeVisible()
  await page.screenshot({ path: 'C:/Users/Administrator/AppData/Local/Temp/ys-all-characters-desktop.png', fullPage: false })
  await page.setViewportSize({ width: 370, height: 850 })
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
  await page.screenshot({ path: 'C:/Users/Administrator/AppData/Local/Temp/ys-all-characters-mobile.png', fullPage: false })
})


  await expect(panel.getByText(/未知第四词条/)).toBeVisible()
  const started = Date.now()
  for (const name of ['芙宁娜', '奈芙尔', '雷电将军']) await panel.getByRole('combobox', { name: '评估角色', exact: true }).selectOption(name)

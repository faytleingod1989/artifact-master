  await expect(panel.getByLabel('+20理论评分范围', { exact: true })).toHaveText('25.0 — 60.1')
  console.log('real worker role switches ms:', Date.now() - started)
  await panel.getByLabel('+20理论评分范围', { exact: true }).scrollIntoViewIfNeeded()
  await page.screenshot({ path: 'C:/Users/Administrator/AppData/Local/Temp/ys-potential-desktop.png' })
  await page.getByRole('button', { name: '查看潜力测试成品', exact: true }).click()
  await expect(panel.getByLabel('+20理论评分范围', { exact: true })).toHaveText('25.0 — 25.0')
  await expect(panel.getByRole('combobox', { name: '评估角色', exact: true })).toHaveValue('雷电将军')

const localPortraits = import.meta.env.DEV || import.meta.env.MODE === 'personal'
  ? (await import('./localPortraits.dev')).localPortraitsByPath : {}
export function getGameCharacterPortrait(name: string): string | undefined {
  if (!import.meta.env.DEV && import.meta.env.MODE !== 'personal') return undefined
  const canonicalName = name.split('·').at(-1) ?? name
  const icon = iconsByName[canonicalName]
  return icon ? localPortraits[`./originals/${icon}.png`] : undefined
}

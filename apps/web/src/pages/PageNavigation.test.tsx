test.each(['success', 'cancel', 'invalid'] as const)('full restore %s resets only committed selection references and retains warehouse preferences', async outcome => {
  const user = await ready()
  await user.type(screen.getByLabelText('搜索圣遗物'), '星海')
  await user.selectOptions(screen.getByLabelText('排序方式'), 'cv')
  await user.click(screen.getByRole('button', { name: '列表视图' }))
  await user.click(screen.getByLabelText('选择星海的指引'))
  await user.click(screen.getByRole('button', { name: '查看星海的指引' }))
  if (outcome === 'cancel') vi.mocked(window.confirm).mockReturnValueOnce(false)
  const replacement = { ...legacyLibrary.find(item => item.name === '星海的指引')!, name: '星海同编号新件' }
  const raw = JSON.stringify({ version: 2, artifacts: [outcome === 'invalid' ? { ...replacement, subs: [null] } : replacement], trash: [], queueIds: [] })
  const file = new File([raw], 'same-id.json', { type: 'application/json' })
  Object.defineProperty(file, 'text', { value: () => Promise.resolve(raw) })
  await user.upload(screen.getByText('导入 JSON').closest('label')!.querySelector('input')!, file)
  await waitFor(() => expect(screen.getByRole('button', { name: '手动录入' })).toBeEnabled())
  await user.click(nav('本地素材'))
  await user.click(nav('圣遗物仓库'))
  expect(screen.getByLabelText('搜索圣遗物')).toHaveValue('星海')
  expect(screen.getByLabelText('排序方式')).toHaveValue('cv')
  expect(screen.getByTestId('warehouse-list')).toBeInTheDocument()
  expect(screen.getByText(outcome === 'success' ? '已选 0 件' : '已选 1 件')).toBeInTheDocument()
  expect(within(screen.getByLabelText('圣遗物详情')).getByText(outcome === 'success' ? '星海同编号新件' : '星海的指引')).toBeInTheDocument()
  if (outcome === 'invalid') expect(window.alert).toHaveBeenCalledWith(expect.stringMatching(/副词条/))
})

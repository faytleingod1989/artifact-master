function nav(name: string) { return within(document.querySelector('.archive-nav')!).getByRole('button', { name }) }

test('element directory filters real profiles and orders rarity before release age in both directions', async () => {
  const user = await ready()
  await user.click(nav('角色配装'))
  await user.click(screen.getByRole('button', { name: /^风元素/ }))
  const names = () => Array.from(document.querySelectorAll('.character-directory [data-character-name]')).map(el => el.getAttribute('data-character-name'))
  expect(names()).toContain('法尔伽')
  expect(names()).not.toContain('雷电将军')
  expect(names().indexOf('法尔伽')).toBeLessThan(names().indexOf('布伦妮'))
  expect(names().indexOf('布伦妮')).toBeLessThan(names().indexOf('雅珂达'))
  await user.selectOptions(screen.getByLabelText('角色新旧排序'), 'oldest')
  expect(names().indexOf('法尔伽')).toBeLessThan(names().indexOf('雅珂达'))
  expect(names().indexOf('雅珂达')).toBeLessThan(names().indexOf('布伦妮'))
  await user.type(screen.getByLabelText('搜索角色'), '不存在的名字')
  expect(screen.getByText('未找到角色，请调整搜索。')).toBeInTheDocument()
  await user.clear(screen.getByLabelText('搜索角色'))
  await user.click(screen.getByRole('button', { name: /法尔伽.*5★/ }))
  expect(screen.getByRole('heading', { name: '法尔伽 · 角色工作台' })).toBeInTheDocument()
})

